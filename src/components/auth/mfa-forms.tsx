"use client";

import { useActionState } from "react";
import {
  beginTotpEnrollment,
  finishFactorReplacement,
  removeVerifiedFactor,
  startFactorReplacement,
  verifyTotpEnrollment,
  verifyTotpLogin,
  type AuthFormState,
} from "@/server/auth/actions";
import {
  AuthMessage,
  authButtonClassName,
  authFieldClassName,
} from "@/components/auth/auth-screen";

const initialState: AuthFormState = {};

export function TotpEnrollmentForm() {
  const [state, action, pending] = useActionState(beginTotpEnrollment, initialState);

  if (state.enrollment) {
    return (
      <EnrollmentChallenge
        enrollment={state.enrollment}
        action={verifyTotpEnrollment}
        submitLabel="Verify and finish setup"
      />
    );
  }

  return (
    <form action={action} className="space-y-4">
      {state.error ? <AuthMessage tone="error">{state.error}</AuthMessage> : null}
      <button className={authButtonClassName} type="submit" disabled={pending}>
        {pending ? "Preparing" : "Create authenticator setup"}
      </button>
    </form>
  );
}

export function TotpVerificationForm({ next }: { next?: string }) {
  const [state, action, pending] = useActionState(verifyTotpLogin, initialState);

  return (
    <form action={action} className="space-y-4">
      {next ? <input type="hidden" name="next" value={next} /> : null}
      <CodeField />
      {state.error ? <AuthMessage tone="error">{state.error}</AuthMessage> : null}
      <button className={authButtonClassName} type="submit" disabled={pending}>
        {pending ? "Checking" : "Verify"}
      </button>
    </form>
  );
}

export function FactorReplacementForm() {
  const [state, startAction, pending] = useActionState(startFactorReplacement, initialState);

  if (state.enrollment) {
    return (
      <EnrollmentChallenge
        enrollment={state.enrollment}
        action={finishFactorReplacement}
        submitLabel="Verify replacement"
        previousFactorId={state.enrollment.previousFactorId}
      />
    );
  }

  return (
    <form action={startAction} className="space-y-4">
      <p className="text-sm leading-6 text-muted">
        Enter a current authenticator code. MediaIQ then shows a new setup key. The current
        authenticator stays active until the new one is verified.
      </p>
      <CodeField id="replacement-code" />
      {state.error ? <AuthMessage tone="error">{state.error}</AuthMessage> : null}
      <button className={authButtonClassName} type="submit" disabled={pending}>
        {pending ? "Checking" : "Start replacement"}
      </button>
    </form>
  );
}

export function FactorRemovalForm({
  factorId,
  canRemove,
}: {
  factorId: string;
  canRemove: boolean;
}) {
  const [state, action, pending] = useActionState(removeVerifiedFactor, initialState);

  if (!canRemove) {
    return (
      <p className="text-sm leading-6 text-muted">
        This is the only authenticator. Removing it would leave the account without MFA, so removal
        is unavailable. Replace it while you still have a current code.
      </p>
    );
  }

  return (
    <form action={action} className="space-y-4">
      <input type="hidden" name="factorId" value={factorId} />
      <CodeField id="removal-code" />
      {state.error ? <AuthMessage tone="error">{state.error}</AuthMessage> : null}
      <button className={authButtonClassName} type="submit" disabled={pending}>
        {pending ? "Removing" : "Remove this authenticator"}
      </button>
    </form>
  );
}

function EnrollmentChallenge({
  enrollment,
  action,
  submitLabel,
  previousFactorId,
}: {
  enrollment: NonNullable<AuthFormState["enrollment"]>;
  action: (
    state: AuthFormState,
    formData: FormData,
  ) => Promise<AuthFormState>;
  submitLabel: string;
  previousFactorId?: string;
}) {
  const [state, formAction, pending] = useActionState(action, initialState);

  return (
    <div className="space-y-4">
      <ol className="list-decimal space-y-2 pl-5 text-sm leading-6 text-muted">
        <li>Open Google Authenticator, Microsoft Authenticator, Apple Passwords, or 1Password.</li>
        <li>Add an account and scan the code, or enter the setup key manually.</li>
        <li>Enter the 6-digit code from the app to finish.</li>
      </ol>
      {/* The SVG is generated by Supabase Auth for this enrollment and is not a remote image. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img
        src={enrollment.qrCode}
        alt="Authenticator setup code"
        className="h-48 w-48 rounded-xl border border-line bg-white p-2"
      />
      <p className="text-sm text-muted">
        Manual setup key
      </p>
      <p className="break-all rounded-xl border border-line bg-canvas px-3 py-2 font-mono text-sm">
        {enrollment.secret}
      </p>
      <form action={formAction} className="space-y-4">
        <input type="hidden" name="factorId" value={enrollment.factorId} />
        {previousFactorId ? (
          <input type="hidden" name="previousFactorId" value={previousFactorId} />
        ) : null}
        <CodeField />
        {state.error ? <AuthMessage tone="error">{state.error}</AuthMessage> : null}
        <button className={authButtonClassName} type="submit" disabled={pending}>
          {pending ? "Checking" : submitLabel}
        </button>
      </form>
    </div>
  );
}

function CodeField({ id = "code" }: { id?: string }) {
  return (
    <label className="block text-sm font-medium" htmlFor={id}>
      Authenticator code
      <input
        id={id}
        name="code"
        inputMode="numeric"
        autoComplete="one-time-code"
        pattern="[0-9]{6}"
        minLength={6}
        maxLength={6}
        required
        className={authFieldClassName}
      />
    </label>
  );
}
